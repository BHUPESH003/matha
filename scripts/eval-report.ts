import * as fs from 'fs/promises'
import * as path from 'path'
import * as os from 'os'
import { fileURLToPath } from 'url'
import { Engine } from '../src/core/engine.js'
import type { MatchContext, MatchResult, MatchType } from '../src/retrieve/match.js'
import { writeFixtureBrain, GOLDEN_QUERIES, FIXED_NOW } from '../tests/eval/fixture.js'
import { runGoldenSet, type EvalMetrics } from '../tests/eval/harness.js'

/**
 * Publishable benchmark report — same methodology matha's own golden-set
 * CI gate (tests/eval/golden.test.ts) already runs, plus a naive-baseline
 * comparison so the number means something on its own (recall@5 alone
 * doesn't say whether structural+lexical scoring earns its keep — the
 * lift over a naive substring match does).
 *
 * The naive matcher below reimplements matha's pre-Phase-2 matching
 * exactly as described in docs/analysis/03-target-architecture.md and the
 * supermemory comparison: case-insensitive substring containment, a
 * >4-char keyword filter, no scoring, no threshold. It exists only for
 * this comparison — never wire it into src/.
 *
 * Run: npm run eval:report
 */

function naiveMatch(engineData: {
  decisions: { id: string; component: string; previous_assumption: string; correction: string; status: string }[]
  dangerZones: { id: string; component: string; description: string; status?: string }[]
  boundaries?: { id: string; component: string; rule: string }[]
  contracts: { component: string; assertions: { description: string }[] }[]
}, ctx: MatchContext): { results: MatchResult[] } {
  const needle = `${ctx.scope} ${ctx.intent} ${(ctx.filepaths ?? []).join(' ')}`.toLowerCase()
  const keywords = needle.split(/\W+/).filter((w) => w.length > 4)
  const isHit = (component: string, text: string) => {
    const hay = `${component} ${text}`.toLowerCase()
    return needle.includes(component.toLowerCase()) || keywords.some((w) => hay.includes(w))
  }
  const result = (matchType: MatchType, recordId: string, component: string): MatchResult => ({
    matchType,
    severity: 'warning',
    title: '',
    description: '',
    source: 'naive-baseline',
    component,
    recommendation: '',
    recordId,
    score: 1,
  })

  const results: MatchResult[] = []
  for (const d of engineData.decisions) {
    if (d.status !== 'active') continue
    if (isHit(d.component, `${d.previous_assumption} ${d.correction}`)) {
      results.push(result('decision_pattern', d.id, d.component))
    }
  }
  for (const z of engineData.dangerZones) {
    if ((z.status ?? 'active') !== 'active') continue
    if (isHit(z.component, z.description)) results.push(result('danger_zone', z.id, z.component))
  }
  for (const b of engineData.boundaries ?? []) {
    if (isHit(b.component, b.rule)) results.push(result('boundary', b.id, b.component))
  }
  for (const c of engineData.contracts) {
    const text = c.assertions.map((a) => a.description).join(' ')
    if (isHit(c.component, text)) results.push(result('contract', `contract:${c.component}`, c.component))
  }
  return { results }
}

function fmt(metrics: EvalMetrics): { recall: string; precision: string; falseCrit: string; p95: string } {
  return {
    recall: metrics.recallAt5.toFixed(3),
    precision: metrics.precisionAt5.toFixed(3),
    falseCrit: metrics.falseCriticalRate.toFixed(3),
    p95: `${metrics.p95LatencyMs.toFixed(2)}ms`,
  }
}

const rootDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')

async function main() {
  const projectDir = await fs.mkdtemp(path.join(os.tmpdir(), 'matha-eval-report-'))
  try {
    const mathaDir = await writeFixtureBrain(projectDir)
    const engine = new Engine(mathaDir)
    const brain = await engine.loadBrain()

    const scored = await runGoldenSet(engine, GOLDEN_QUERIES, FIXED_NOW)
    const naive = await runGoldenSet(engine, GOLDEN_QUERIES, FIXED_NOW, async (_e, ctx) =>
      naiveMatch(brain, ctx),
    )

    const s = fmt(scored)
    const n = fmt(naive)
    const pkg = JSON.parse(await fs.readFile(path.join(rootDir, 'package.json'), 'utf-8'))

    const activeDecisions = brain.decisions.filter((d) => d.status === 'active').length

    const report = `# matha retrieval benchmark

Generated by \`npm run eval:report\` against \`${pkg.name}@${pkg.version}\` — reproducible, no external
data or network access. This is matha's own golden-set eval (the CI gate in
\`tests/eval/golden.test.ts\`), run standalone and compared against a naive
baseline so the headline number means something on its own.

**Not a public benchmark.** There is no published academic dataset for
"does this dev-tool retrieve the right decision for a given file + intent" —
that's a narrower, more structural task than conversational long-memory QA
(the domain LongMemEval/LoCoMo-style benchmarks target). This is an in-house
fixture, the same kind of evidence agentmemory's own \`coding-agent-life-v1\`
corpus is, not a claim of parity with a public leaderboard.

## Corpus

Synthetic fixture brain (\`tests/eval/fixture.ts\`) — a fictional payment
service, deliberately including retired/uncertain/text-only-component
records so a naive matcher and a scoring one diverge:

| Record type | Count |
|---|---|
| Decisions (active) | ${activeDecisions} |
| Decisions (retired, must never surface) | ${brain.decisions.length - activeDecisions} |
| Danger zones | ${brain.dangerZones.length} |
| Boundaries | ${(brain.boundaries ?? []).length} |
| Contracts (assertions) | ${brain.contracts.length} (${brain.contracts.reduce((n, c) => n + c.assertions.length, 0)}) |
| Queries | ${GOLDEN_QUERIES.length} |

## Method

Each query provides \`(scope, intent, filepaths)\` and the record ids expected
in the top 5 results. Two matchers run over the identical corpus and queries:

- **scored (current)** — matha's actual retrieval: structural path score ×
  lexical (BM25) score × confidence weight × recency decay (\`src/retrieve/match.ts\`).
- **naive baseline** — matha's pre-Phase-2 behaviour: case-insensitive
  substring containment between the query and each record's component/text,
  a >4-char keyword filter, no scoring or threshold.

recall@5 and precision@5 are computed identically for both (see
\`tests/eval/harness.ts\` — the matcher is the only pluggable part).

## Results

| Metric | Naive baseline | Scored (current) |
|---|---|---|
| recall@5 | ${n.recall} | **${s.recall}** |
| precision@5 | ${n.precision} | **${s.precision}** |
| false-critical rate\\* | ${n.falseCrit} | **${s.falseCrit}** |
| p95 match latency (warm) | ${n.p95} | **${s.p95}** |

\\* Not a fair comparison: the naive baseline here never assigns \`critical\`
severity at all (it has no structural-hit concept to gate it on), so its
false-critical rate is trivially zero by construction — not evidence it is
equally safe. It's included for completeness, not as a claimed win.

Brief token budget (scored only — the naive baseline never assembles a
budgeted brief): **${scored.briefTokenMax} / ${scored.briefBudget}** tokens, worst case
across all ${GOLDEN_QUERIES.length} queries.

## Reproduce

\`\`\`bash
npm run eval:report
\`\`\`

Deterministic: the fixture clock is fixed (\`FIXED_NOW\` in \`tests/eval/fixture.ts\`),
so recall/precision/false-critical are exactly reproducible. Latency will
vary slightly by machine.
`

    const outPath = path.join(rootDir, 'BENCHMARKS.md')
    await fs.writeFile(outPath, report, 'utf-8')
    console.log(report)
    console.log(`\n✓ Written to ${outPath}`)
  } finally {
    await fs.rm(projectDir, { recursive: true, force: true })
  }
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
